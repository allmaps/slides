export type InterfaceKey = keyof typeof interfaceDefaults;
export type InterfaceText = (key: InterfaceKey, values?: Record<string, string | number>) => string;
export const createInterfaceText = (config: () => InterfaceConfig | undefined = () => undefined): InterfaceText =>
  (key, values = {}) => {
    const settings = config();
    const legacy = settings?.startScreen as Record<string, string | undefined> | undefined;
    const template = settings?.text?.[key] ?? legacy?.[key] ?? interfaceDefaults[key];
    return template.replace(/\{(\w+)\}/g, (match, name) => values[name] === undefined ? match : String(values[name]));
  };
